"""Regenerates the reference parts of the developer documentation from the code, so they never drift:

    docs/ERROR_CODES.md   every error code the API can return, its HTTP status, message and the file:line that raises it
    docs/API.md           every route: method, path, permission, what it does (docstring)
    docs/SCHEMA.md        every table and column from the SQLAlchemy models (what Alembic migrates to)

Run from backend/:   python scripts/gen_docs.py        (no database needed)
"""
import ast
import inspect
import os
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT.parent / 'docs'
sys.path.insert(0, str(ROOT))
os.environ.setdefault('SECRET_KEY', 'docs')
STATUS = {'bad': 400, 'denied': 403, 'not_found': 404, 'conflict': 409}
DEFAULT_CODE = {'bad': 'invalid', 'denied': 'forbidden', 'not_found': 'not_found', 'conflict': 'conflict'}


def _text(node):
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.JoinedStr):
        return ''.join(v.value if isinstance(v, ast.Constant) else '{…}' for v in node.values)
    return '…'


def errors():
    found = defaultdict(lambda: {'status': None, 'messages': set(), 'where': []})
    for path in sorted((ROOT / 'kz').rglob('*.py')):
        tree = ast.parse(path.read_text(), str(path))
        for n in ast.walk(tree):
            if not isinstance(n, ast.Call):
                continue
            fn = n.func.id if isinstance(n.func, ast.Name) else n.func.attr if isinstance(n.func, ast.Attribute) else None
            if fn == 'ApiError' and len(n.args) >= 2 and isinstance(n.args[0], ast.Constant):
                status, code, msg = n.args[0].value, _text(n.args[1]), _text(n.args[2]) if len(n.args) > 2 else ''
            elif fn in STATUS:
                kw = {k.arg: k.value for k in n.keywords}
                code_node = n.args[1] if len(n.args) > 1 else kw.get('code')
                code = _text(code_node) if code_node is not None else DEFAULT_CODE[fn]
                msg = _text(n.args[0]) if n.args else _text(kw.get('msg', ast.Constant('')))
                status = STATUS[fn]
            else:
                continue
            if code in ('…', ''):
                continue
            e = found[code]
            e['status'] = e['status'] or status
            if msg and msg != '…':
                e['messages'].add(msg)
            e['where'].append(f'{path.relative_to(ROOT)}:{n.lineno}')
    return found


def write_errors():
    found = errors()
    out = ['# Error codes', '', 'Generated by `backend/scripts/gen_docs.py` — do not edit by hand. Every API error is JSON `{"error": "<code>", "message": "..."}`;',
           'the screen shows the message. Find the code below to see where it is raised; docs/TROUBLESHOOTING.md explains how to fix the common ones.', '',
           '| Code | HTTP | Message (as the user sees it) | Raised in |', '|---|---|---|---|']
    for code in sorted(found):
        e = found[code]
        msgs = ' / '.join(sorted(e['messages']))[:400].replace('|', '\\|') or '—'
        where = ', '.join(f'`{w}`' for w in e['where'][:6]) + (f' (+{len(e["where"]) - 6})' if len(e['where']) > 6 else '')
        out.append(f'| `{code}` | {e["status"]} | {msgs} | {where} |')
    (DOCS / 'ERROR_CODES.md').write_text('\n'.join(out) + '\n')
    return len(found)


def write_api():
    from kz import create_app
    app = create_app()
    rows = []
    for r in sorted(app.url_map.iter_rules(), key=lambda r: (r.rule, sorted(r.methods))):
        if r.endpoint == 'static':
            continue
        fn = app.view_functions[r.endpoint]
        perm = 'public'
        mod = sys.modules[inspect.unwrap(fn).__module__]
        lines = inspect.getsource(mod).split('\n')
        name = inspect.unwrap(fn).__name__
        for i, ln in enumerate(lines):
            if ln.startswith(f'def {name}('):
                deco = [x.strip() for x in lines[max(0, i - 4):i] if x.strip().startswith('@')]
                req = [d for d in deco if d.startswith('@require(') or d.startswith('@login_required') or d.startswith('@parent_required')]
                perm = ', '.join(d.replace('@require(', '').rstrip(')').replace("'", '') if d.startswith('@require(') else
                                 ('signed in' if 'login' in d else 'parent signed in') for d in req) or 'public'
                if any(d.startswith('@high_risk') for d in deco):
                    perm += ' + password re-entry'
                break
        doc = (inspect.getdoc(inspect.unwrap(fn)) or '').split('\n')[0] or (
            {'GET': 'List / read', 'POST': 'Create / act', 'PUT': 'Update', 'DELETE': 'Delete'}.get(sorted(m for m in r.methods if m not in ('HEAD', 'OPTIONS'))[0], '') +
            ': ' + name.replace('_', ' ').strip())
        methods = ','.join(sorted(m for m in r.methods if m not in ('HEAD', 'OPTIONS')))
        rows.append(f'| {methods} | `{r.rule}` | {perm} | {doc.replace("|", "/")} | `{mod.__name__.replace("kz.", "")}.{name}` |')
    out = ['# API reference', '', 'Generated by `backend/scripts/gen_docs.py`. Base URL: `https://<domain>`. Bodies and responses are JSON',
           '(except file uploads, which are multipart). Permission `action, screen` means the user\'s roles must grant that action on that screen',
           '(Setup → Roles & permissions). Errors: docs/ERROR_CODES.md.', '', f'{len(rows)} routes.', '',
           '| Method | Path | Permission | Purpose | Code |', '|---|---|---|---|---|'] + rows
    (DOCS / 'API.md').write_text('\n'.join(out) + '\n')
    return len(rows)


def write_schema():
    from kz.models import Base
    out = ['# Database schema', '', 'Generated by `backend/scripts/gen_docs.py` from `backend/kz/models/`. Alembic migrations in',
           '`backend/migrations/versions/` create exactly this. Conventions and posting rules: docs/DATABASE.md.', '']
    for t in sorted(Base.metadata.tables.values(), key=lambda t: t.name):
        out += [f'## `{t.name}`', '', '| Column | Type | Null | Default | Key / reference | Note |', '|---|---|---|---|---|---|']
        for c in t.columns:
            key = 'PK' if c.primary_key else ''
            if c.foreign_keys:
                key += (' ' if key else '') + '→ ' + ', '.join(f.target_fullname for f in c.foreign_keys)
            if c.unique:
                key += ' unique'
            dflt = c.server_default.arg if c.server_default is not None and hasattr(c.server_default, 'arg') else ''
            dflt = getattr(dflt, 'text', dflt)
            out.append(f'| `{c.name}` | {str(c.type).split("(")[0] if "VARIANT" in str(c.type).upper() else c.type} | {"yes" if c.nullable else ""} | {dflt} | {key} | {c.comment or ""} |')
        idx = [i for i in t.indexes]
        if idx:
            out += ['', 'Indexes: ' + ', '.join(f'`{i.name}` ({", ".join(c.name for c in i.columns)})' for i in idx)]
        out.append('')
    (DOCS / 'SCHEMA.md').write_text('\n'.join(out) + '\n')
    return len(Base.metadata.tables)


if __name__ == '__main__':
    DOCS.mkdir(exist_ok=True)
    print(f'{write_errors()} error codes, {write_api()} routes, {write_schema()} tables written to {DOCS}')
